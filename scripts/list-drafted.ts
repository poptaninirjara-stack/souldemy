// Writes docs/GAME_ITEMS_FOR_REVIEW.md: every game item drafted for the games (d: true),
// grouped by game, so the course author can review them in one place.
// Run: npm run drafted
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import type { Game } from '../src/types/game.ts'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const { games } = JSON.parse(readFileSync(join(root, 'content', 'games.json'), 'utf8')) as { games: Game[] }

const lines: string[] = [
  '# Game items for the author\'s review',
  '',
  'Generated by `npm run drafted` from `content/games.json`.',
  '',
  'What needs review:',
  '',
  '- **The items listed below** were drafted for the practice games.',
  '- **All feedback text in every game** (the "why" explanations, the scenario replies, intros and endings) was also drafted, including in the items that are not listed.',
  '- **Two games are generated automatically** from the author\'s own tables and need no review beyond the tables themselves: the task-word decoder and the "Right phrase, right moment" games.',
  '',
  'To change an item, edit `content/games.json` and rerun `npm run content`. Delete `"d": true` from an item once it has been approved.',
  '',
]

for (const g of games) {
  const items =
    g.kind === 'scenario'
      ? g.steps.flatMap((s, i) => s.choices.filter((c) => c.d).map((c) => `Step ${i + 1} (${c.good ? 'good' : 'weaker'} choice): ${c.text}`))
      : g.kind === 'sort'
        ? g.items.filter((it) => it.d).map((it) => `${it.text} → **${g.bins.find((b) => b.id === it.bin)?.label}**`)
        : g.items.filter((it) => it.d).map((it) => `${it.prompt} → **${it.options[it.correct]}** (other options: ${it.options.filter((_, k) => k !== it.correct).join(' / ')})`)
  lines.push(`## ${g.title} (\`${g.id}\`)`, '', `Source: ${g.source}.`, '')
  if (items.length) lines.push(...items.map((t) => `- ${t}`))
  else lines.push('- No drafted items; only the feedback lines need review.')
  lines.push('')
}

writeFileSync(join(root, 'docs', 'GAME_ITEMS_FOR_REVIEW.md'), lines.join('\n'))
console.log('Wrote docs/GAME_ITEMS_FOR_REVIEW.md')
